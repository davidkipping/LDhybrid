def _unpack(s, shape, dtype):
    return np.frombuffer(zlib.decompress(base64.b64decode(s)), dtype).astype(float).reshape(shape)


def _grid():
    """The tensor grid: the models (scaled), their rows, the axes, and the value
    of every grid node (a model, the mix of two models in _FILL, or NaN)."""
    X = _unpack(_GRID, (_N, 3), "<f8") / SCALE
    Y = _unpack(_DATA, (_N, NW + 2), "<f4")
    axes = [np.unique(np.round(X[:, k], 9)) for k in range(3)]
    shape = tuple(len(a) for a in axes)
    ijk = np.stack([np.searchsorted(a, np.round(X[:, k], 9)) for k, a in enumerate(axes)], -1)
    Yn = np.full((int(np.prod(shape)), Y.shape[1]), np.nan)
    Yn[np.ravel_multi_index(tuple(ijk.T), shape)] = Y
    for node, a, b, t in _FILL:
        Yn[node] = (1 - t) * Y[a] + t * Y[b]
    return X, Y, axes, shape, Yn


_X, _Y, _AXES, _SHAPE, _YN = _grid()
_VALID = np.isfinite(_YN[:, 0])
_YN0 = np.where(_VALID[:, None], _YN, 0.0)

_X0 = _X - _X.min(0)                    # the nearest-model search, in small numbers
_CONST = {}
_MU = np.linspace(0.0, 1.0, 2001)
_BASIS_T = np.eye(NW)
_LAW_CONST = {}


def _const(dt):
    """The tables as mx.arrays of dtype dt (made once per dtype)."""
    if dt not in _CONST:
        f = lambda a: mx.array(np.asarray(a, float), dtype=dt)
        _CONST[dt] = dict(X0=f(_X0), lo=f(_X.min(0)), Y=f(_Y), YN=f(_YN0), valid=mx.array(_VALID),
                          axes=[f(a) for a in _AXES], scale=f(SCALE), basis=f(_BASIS_T),
                          mu=f(_MU), eps=[float(e) for e in EPS],
                          **{k: f(v) for k, v in _LAW_CONST.items()})
    return _CONST[dt]


def _dtype(*args):
    """float32 if a float32 array is among args and no float64 one; else float64."""
    kinds = set()
    for a in args:
        if isinstance(a, mx.array):
            kinds.add("32" if a.dtype in (mx.float32, mx.float16, mx.bfloat16) else "64")
        elif isinstance(a, (np.ndarray, np.generic)):
            kinds.add("32" if a.dtype == np.float32 else "64")
    return mx.float32 if kinds == {"32"} else mx.float64


def _stream(dt):
    # MLX has no float64 on Metal: float64 work runs on the CPU stream
    return mx.stream(mx.cpu) if dt == mx.float64 else contextlib.nullcontext()


def _as(a, dt):
    if isinstance(a, mx.array):
        return a if a.dtype == dt else a.astype(dt)
    return mx.array(np.asarray(a, float), dtype=dt)


def _pole(mu, e):
    return ((mu * mu + e) ** -2 - (1 + e) ** -2) / (e ** -2 - (1 + e) ** -2)


def _shapes(mu, K):
    r = mx.sqrt(mu)
    return mx.stack([1 - r, 1 - mu, 1 - mu * r, 1 - mu * mu], axis=-1)

def _intensity(c, mu, K):
    return 1.0 - c @ mx.transpose(_shapes(mu, K))


def _is_physical(c, K, dt):
    tol = 1e-10 if dt == mx.float64 else 1e-6           # float32 rounding of I near mu = 1
    I = _intensity(c, K["mu"], K)
    return (mx.all(mx.isfinite(I), axis=-1) & (I[..., 0] >= -tol)
            & mx.all(I[..., 1:] - I[..., :-1] >= -tol, axis=-1))


def _interpolate(x, extrapolate, K, dt):
    """Linear interpolation at scaled points x (n, 3): (n, NW + 2) values and
    the inside flag. The Kuhn tetrahedron of the grid box containing x is the
    one given by the order of x's fractional coordinates in the box."""
    tol = 1e-9 if dt == mx.float64 else 1e-5
    ii, ff = [], []
    for k, a in enumerate(K["axes"]):
        xk = x[:, k]
        i = mx.stop_gradient(mx.minimum((xk[:, None] >= a[None, 1:-1]).sum(-1),
                                        a.shape[0] - 2).astype(mx.int32))
        ii.append(i)
        ff.append((xk - a[i]) / (a[i + 1] - a[i]))
    i, f = mx.stack(ii, -1), mx.stack(ff, -1)
    inside = mx.all((f >= -tol) & (f <= 1 + tol), axis=-1)
    order = mx.stop_gradient(mx.argsort(-f, axis=-1))       # indices: no gradient
    fs = mx.take_along_axis(f, order, axis=-1)
    lam = mx.stack([1 - fs[:, 0], fs[:, 0] - fs[:, 1], fs[:, 1] - fs[:, 2], fs[:, 2]], -1)
    E = mx.eye(3, dtype=mx.int32)
    v = [i]
    for j in range(3):
        v.append(v[-1] + E[order[:, j]])
    v = mx.stack(v, 1)                                      # (n, 4, 3) grid indices
    node = mx.stop_gradient((v[..., 0] * _SHAPE[1] + v[..., 1]) * _SHAPE[2] + v[..., 2])
    inside = inside & ~mx.any((lam > tol) & ~K["valid"][node], axis=-1)
    y = (lam[..., None] * K["YN"][node]).sum(1)
    if extrapolate:
        x0, X0 = x - K["lo"], K["X0"]
        d2 = (x0 * x0).sum(-1, keepdims=True) - 2.0 * (x0 @ mx.transpose(X0)) + (X0 * X0).sum(-1)
        y = mx.where(inside[:, None], y, K["Y"][mx.stop_gradient(mx.argmin(d2, axis=-1))])
    else:
        y = mx.where(inside[:, None], y, mx.nan)
    return y, inside


def coefficients(teff, logg, mh, extrapolate=False):
    """Interpolated Claret four-parameter coefficients at (Teff [K], log g [cgs], [M/H]):
    numbers, numpy or mx arrays, broadcast against each other. Returns
    dict(coeffs, physical, mu_cri, lc_ppm, inside) of mx.arrays,
    coeffs with a trailing axis of 4. Outside the grid the outputs are
    NaN (inside False) unless extrapolate=True, which uses the nearest model."""
    dt = _dtype(teff, logg, mh)
    with _stream(dt):
        K = _const(dt)
        t, g, m = mx.broadcast_arrays(_as(teff, dt), _as(logg, dt), _as(mh, dt))
        shape = t.shape
        x = mx.stack([t.reshape(-1), g.reshape(-1), m.reshape(-1)], axis=-1) / K["scale"]
        y, inside = _interpolate(x, extrapolate, K, dt)
        c = y[:, :NW]
        cs = c.reshape(shape + (NW,))
        return dict(coeffs=cs,
                    physical=_is_physical(c, K, dt).reshape(shape), mu_cri=y[:, NW].reshape(shape),
                    lc_ppm=y[:, NW + 1].reshape(shape), inside=inside.reshape(shape))


def shapes(mu):
    """The law's shapes at mu (m,): shape (m, NW)."""
    dt = _dtype(mu)
    with _stream(dt):
        return _shapes(_as(mu, dt), _const(dt))


def intensity(c, mu):
    """I(mu)/I(1) for Claret four-parameter coefficients c (..., 4) at mu (m,): shape (..., m)."""
    dt = _dtype(c, mu)
    with _stream(dt):
        return _intensity(_as(c, dt), _as(mu, dt), _const(dt))


def is_physical(c):
    """Positive and non-increasing towards the limb on 2001 points in mu: shape (...)."""
    dt = _dtype(c)
    with _stream(dt):
        return _is_physical(_as(c, dt), _const(dt), dt)


