def _unpack(s, shape, dtype):
    return np.frombuffer(zlib.decompress(base64.b64decode(s)), dtype).astype(float).reshape(shape)


_X = _unpack(_GRID, (_N, 3), "<f8") / SCALE
_Y = _unpack(_DATA, (_N, 6), "<f4")
_LIN = LinearNDInterpolator(_X, _Y)
_NEAR = None


def _pole(mu, e):
    return ((mu * mu + e) ** -2 - (1 + e) ** -2) / (e ** -2 - (1 + e) ** -2)


def shapes(mu):
    """T_j(mu), shape (len(mu), 4)."""
    mu = np.asarray(mu, float)
    return np.stack([1 - mu ** 4, (1 - mu ** 2) ** 2, _pole(mu, EPS[0]), _pole(mu, EPS[1])], axis=-1)


def intensity(w, mu):
    """I(mu)/I(1) for hybrid4 weights w."""
    return 1 - shapes(mu) @ np.asarray(w, float)


def is_physical(w, n=2001):
    """Positive and non-increasing towards the limb on a dense grid."""
    I = intensity(w, np.linspace(0.0, 1.0, n))
    return bool(I[0] >= -1e-10 and np.all(np.diff(I) >= -1e-10))


def coefficients(teff, logg, mh, extrapolate=False):
    """Interpolated hybrid4 weights at (Teff [K], log g [cgs], [M/H]).

    extrapolate=True uses the nearest model outside the grid (else ValueError).
    Returns dict(w, physical, mu_cri, lc_ppm, inside)."""
    global _NEAR
    x = np.array([[teff, logg, mh]]) / SCALE
    y = _LIN(x)[0]
    inside = bool(np.all(np.isfinite(y)))
    if not inside:
        if not extrapolate:
            raise ValueError(f"({teff}, {logg}, {mh}) is outside the {GRID} grid; "
                             "pass extrapolate=True to use the nearest model")
        if _NEAR is None:
            _NEAR = NearestNDInterpolator(_X, _Y)
        y = _NEAR(x)[0]
    w = y[:4].copy()
    return dict(w=tuple(float(v) for v in w), physical=is_physical(w), mu_cri=float(y[4]),
                lc_ppm=float(y[5]), inside=inside)


