def _unpack(s, shape, dtype):
    return np.frombuffer(zlib.decompress(base64.b64decode(s)), dtype).astype(float).reshape(shape)


def _grid():
    """The tensor grid: the models (scaled), their rows, the axes, and the value
    of every grid node (a model, the mix of two models in _FILL, or NaN)."""
    X = _unpack(_GRID, (_N, 3), "<f8") / SCALE
    Y = _unpack(_DATA, (_N, NW + 2), "<f4")
    axes = [np.unique(np.round(X[:, k], 9)) for k in range(3)]
    shape = tuple(len(a) for a in axes)
    ijk = np.stack([np.searchsorted(a, np.round(X[:, k], 9)) for k, a in enumerate(axes)], -1)
    Yn = np.full((int(np.prod(shape)), Y.shape[1]), np.nan)
    Yn[np.ravel_multi_index(tuple(ijk.T), shape)] = Y
    for node, a, b, t in _FILL:
        Yn[node] = (1 - t) * Y[a] + t * Y[b]
    return X, Y, axes, shape, Yn


_X, _Y, _AXES, _SHAPE, _YN = _grid()
_VALID = np.isfinite(_YN[:, 0])
_YN0 = np.where(_VALID[:, None], _YN, 0.0)


def _corners(x):
    """The Kuhn tetrahedron of each scaled point x (m, 3): its grid nodes (m, 4),
    barycentric weights (m, 4) and the inside flag (m,). The box containing x
    is split by the order of x's fractional coordinates in it, the same split
    in every box, so the interpolant is continuous."""
    i = np.stack([np.clip(np.searchsorted(a, x[:, k], side="right") - 1, 0, len(a) - 2)
                  for k, a in enumerate(_AXES)], -1)
    f = np.stack([(x[:, k] - a[i[:, k]]) / (a[i[:, k] + 1] - a[i[:, k]])
                  for k, a in enumerate(_AXES)], -1)
    inside = np.all((f >= -1e-9) & (f <= 1 + 1e-9), axis=1)
    order = np.argsort(-f, axis=1, kind="stable")
    fs = np.take_along_axis(f, order, axis=1)
    lam = np.column_stack([1 - fs[:, 0], fs[:, 0] - fs[:, 1], fs[:, 1] - fs[:, 2], fs[:, 2]])
    v = np.repeat(i[:, None, :], 4, axis=1)
    for j in range(3):
        v[:, j + 1:, :] += np.eye(3, dtype=int)[order[:, j]][:, None, :]
    node = (v[..., 0] * _SHAPE[1] + v[..., 1]) * _SHAPE[2] + v[..., 2]
    inside &= ~np.any((lam > 1e-9) & ~_VALID[node], axis=1)
    return node, lam, inside


def _interpolate(x):
    """Interpolated rows at scaled points x (m, 3); NaN outside the grid."""
    node, lam, inside = _corners(x)
    y = (lam[..., None] * _YN0[node]).sum(1)
    y[~inside] = np.nan
    return y


def _pole(mu, e):
    return ((mu * mu + e) ** -2 - (1 + e) ** -2) / (e ** -2 - (1 + e) ** -2)


def _basis():
    """Rows: S1..S4 on (1 - mu^4, (1 - mu^2)^2, P_e0, P_e1); with g = dI/dx,
    S3: I(0) = 0, g(1) = g'(1) = g''(1) = 0; S4: I(0) = 0, g(1) = g'(1) = g''(0) = 0."""
    (e0, e1), (a0, a1) = EPS, (1 / (e ** -2 - (1 + e) ** -2) for e in EPS)
    g = lambda x: [2 * x, 2 * (1 - x), 2 * a0 * (x + e0) ** -3, 2 * a1 * (x + e1) ** -3]
    g1 = lambda x: [2.0, -2.0, -6 * a0 * (x + e0) ** -4, -6 * a1 * (x + e1) ** -4]
    g2 = lambda x: [0.0, 0.0, 24 * a0 * (x + e0) ** -5, 24 * a1 * (x + e1) ** -5]
    S3 = np.linalg.solve([[1.0] * 4, g(1.0), g1(1.0), g2(1.0)], [1.0, 0, 0, 0])
    S4 = np.linalg.solve([[1.0] * 4, g(1.0), g1(1.0), g2(0.0)], [1.0, 0, 0, 0])
    return np.array([[0.5, 0.5, 0, 0], [0, 1.0, 0, 0], S3, S4])


BASIS = _basis()


def shapes(mu):
    """S_k(mu), shape (len(mu), 4)."""
    mu = np.asarray(mu, float)
    T = np.stack([1 - mu ** 4, (1 - mu ** 2) ** 2, _pole(mu, EPS[0]), _pole(mu, EPS[1])], axis=-1)
    return T @ BASIS.T


def from_q(q):
    """Weights from sampling coordinates q in [0, 1]^4 (vectorised over rows)."""
    q = np.asarray(q, float)
    s, a, b = q[..., 0] ** 0.25, q[..., 1] ** (1 / 3), q[..., 2] ** 0.5
    return np.stack([s * (1 - a), s * a * (1 - b), s * a * b * (1 - q[..., 3]), s * a * b * q[..., 3]], -1)


def to_q(w):
    """Sampling coordinates of one set of weights (outside [0, 1] if outside the region)."""
    w = np.asarray(w, float)
    s = w.sum()
    if s == 0:
        return (0.0, 0.0, 0.0, 0.0)
    f = w / s
    r1 = 1 - f[0]
    r2 = 1 - f[1] / r1 if r1 != 0 else 0.0
    f34 = f[2] + f[3]
    q = np.array([np.sign(s) * abs(s) ** 4, np.sign(r1) * abs(r1) ** 3,
                  r2 * r2 if r2 >= 0 else r2, f[3] / f34 if f34 != 0 else 0.0])
    q = np.where((q < 0) & (q > -1e-9), 0.0, q)            # rounding noise onto the bound
    return tuple(float(v) for v in np.where((q > 1) & (q < 1 + 1e-9), 1.0, q))


def intensity(w, mu):
    """I(mu)/I(1) for hybrid4 coefficients w."""
    return 1 - shapes(mu) @ np.asarray(w, float)


def is_physical(w, n=2001):
    """Positive and non-increasing towards the limb on a dense grid."""
    with np.errstate(all="ignore"):
        I = intensity(w, np.linspace(0.0, 1.0, n))
    return bool(np.all(np.isfinite(I)) and I[0] >= -1e-10 and np.all(np.diff(I) >= -1e-10))


def coefficients(teff, logg, mh, extrapolate=False):
    """Interpolated hybrid4 coefficients at (Teff [K], log g [cgs], [M/H]).

    extrapolate=True uses the nearest model outside the grid (else ValueError).
    Returns dict(coeffs, w, q, physical, mu_cri, lc_ppm, inside)."""
    x = np.array([[teff, logg, mh]], float) / SCALE
    y = _interpolate(x)[0]
    inside = bool(np.all(np.isfinite(y)))
    if not inside:
        if not extrapolate:
            raise ValueError(f"({teff}, {logg}, {mh}) is outside the {GRID} grid; "
                             "pass extrapolate=True to use the nearest model")
        y = _Y[np.argmin(((_X - x) ** 2).sum(1))]
    c = y[:NW].copy()
    c = tuple(float(v) for v in c)
    return dict(coeffs=c, w=c, q=to_q(c), physical=is_physical(c), mu_cri=float(y[NW]),
                lc_ppm=float(y[NW + 1]), inside=inside)


