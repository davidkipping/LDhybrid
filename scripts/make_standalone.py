"""Write lightweight, single-file hybrid4 interpolators for one grid and one
passband, with the coefficient grid embedded (numpy + scipy only).

    .venv/bin/python scripts/make_standalone.py      -> standalone/*.py

Each file reproduces ldhybrid.interpolate.LDTables.coefficients for that grid
and band (r-weighted method): linear interpolation on a Delaunay triangulation
of (Teff/100, log g/0.5, [M/H]/0.5). The MPS-ATLAS files also embed the MURaM
magnetic Δw corrections for the band.
"""

