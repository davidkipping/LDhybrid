H5_DOC = '''Law (hybrid5):
    I(mu)/I(1) = 1 - w1 (1 - mu^4) - w2 (1 - mu^2)^2 - w3 P(mu; e0) - w4 P(mu; e1) - w5 P(mu; e2)
    P(mu; e) = [(mu^2 + e)^-2 - (1 + e)^-2] / [e^-2 - (1 + e)^-2]
    e0, e1, e2 = {eps0}, {eps1}, {eps2}
Every shape falls from 1 at the limb to 0 at the centre, so the simplex
w >= 0, sum(w) <= 1 holds profiles with I(0) >= 0 that are non-increasing
towards the limb (a sufficient region: it is smaller than the set of all
positive monotonic hybrid5 profiles). Sampling coordinates: stick-breaking of
a flat Dirichlet, w_j = (1 - q_j^(1/(6-j))) prod_(i<j) q_i^(1/(6-i)),
j = 1..5; uniform q is a uniform prior over the simplex.'''

H5_CODE = '''def shapes(mu):
    """(1 - mu^4, (1 - mu^2)^2, P_e0, P_e1, P_e2), shape (len(mu), 5)."""
    mu = np.asarray(mu, float)
    return np.stack([1 - mu ** 4, (1 - mu ** 2) ** 2] + [_pole(mu, e) for e in EPS], axis=-1)


def from_q(q):
    """Weights from sampling coordinates q in [0, 1]^5 (vectorised over rows)."""
    q = np.asarray(q, float)
    n, out, stick = q.shape[-1], [], 1.0
    for j in range(n):
        r = q[..., j] ** (1.0 / (n - j))
        out.append(stick * (1 - r))
        stick = stick * r
    return np.stack(out, -1)


def to_q(w):
    """Sampling coordinates of one set of weights (outside [0, 1] if outside the simplex)."""
    w = np.asarray(w, float)
    n, q, stick = w.size, np.empty(w.size), 1.0
    for j in range(n):
        f = 1.0 - w[j] / stick if stick > 0 else 1.0
        q[j] = f ** (n - j) if f >= 0 else f               # a negative f stays negative
        stick = stick * f if f > 0 else 0.0
    q = np.where((q < 0) & (q > -1e-9), 0.0, q)            # rounding noise onto the bound
    return tuple(float(v) for v in np.where((q > 1) & (q < 1 + 1e-9), 1.0, q))'''

