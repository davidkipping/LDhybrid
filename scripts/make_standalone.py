def fill_block(G):
    """_FILL for a GridSimplex: (node, model_lo, model_hi, t) of each filled node."""
    rows = [(int(n), int(G.node_idx[n, 0]), int(G.node_idx[n, 1]), float(G.node_w[n, 1]))
            for n in np.flatnonzero(G.node_w[:, 1] > 0)]
