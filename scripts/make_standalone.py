def _unpack(s, shape, dtype):
    return np.frombuffer(zlib.decompress(base64.b64decode(s)), dtype).astype(float).reshape(shape)


_X = _unpack(_GRID, (_N, 3), "<f8") / SCALE
_Y = _unpack(_DATA, (_N, 6), "<f4")
_LIN = LinearNDInterpolator(_X, _Y)
_NEAR = None


def _pole(mu, e):
    return ((mu * mu + e) ** -2 - (1 + e) ** -2) / (e ** -2 - (1 + e) ** -2)


def _basis():
    """Rows: S1..S4 on (1 - mu^4, (1 - mu^2)^2, P_e0, P_e1); with g = dI/dx,
    S3: I(0) = 0, g(1) = g'(1) = g''(1) = 0; S4: I(0) = 0, g(1) = g'(1) = g''(0) = 0."""
    (e0, e1), (a0, a1) = EPS, (1 / (e ** -2 - (1 + e) ** -2) for e in EPS)
    g = lambda x: [2 * x, 2 * (1 - x), 2 * a0 * (x + e0) ** -3, 2 * a1 * (x + e1) ** -3]
    g1 = lambda x: [2.0, -2.0, -6 * a0 * (x + e0) ** -4, -6 * a1 * (x + e1) ** -4]
    g2 = lambda x: [0.0, 0.0, 24 * a0 * (x + e0) ** -5, 24 * a1 * (x + e1) ** -5]
    S3 = np.linalg.solve([[1.0] * 4, g(1.0), g1(1.0), g2(1.0)], [1.0, 0, 0, 0])
    S4 = np.linalg.solve([[1.0] * 4, g(1.0), g1(1.0), g2(0.0)], [1.0, 0, 0, 0])
    return np.array([[0.5, 0.5, 0, 0], [0, 1.0, 0, 0], S3, S4])


BASIS = _basis()


def shapes(mu):
    """S_k(mu), shape (len(mu), 4)."""
    mu = np.asarray(mu, float)
    T = np.stack([1 - mu ** 4, (1 - mu ** 2) ** 2, _pole(mu, EPS[0]), _pole(mu, EPS[1])], axis=-1)
    return T @ BASIS.T


def from_q(q):
    """Weights from sampling coordinates q in [0, 1]^4 (vectorised over rows)."""
    q = np.asarray(q, float)
    s, a, b = q[..., 0] ** 0.25, q[..., 1] ** (1 / 3), q[..., 2] ** 0.5
    return np.stack([s * (1 - a), s * a * (1 - b), s * a * b * (1 - q[..., 3]), s * a * b * q[..., 3]], -1)


def to_q(w):
    """Sampling coordinates of one set of weights (outside [0, 1] if outside the region)."""
    w = np.asarray(w, float)
    s = w.sum()
    if s == 0:
        return (0.0, 0.0, 0.0, 0.0)
    f = w / s
    r1 = 1 - f[0]
    r2 = 1 - f[1] / r1 if r1 != 0 else 0.0
    f34 = f[2] + f[3]
    q = np.array([np.sign(s) * abs(s) ** 4, np.sign(r1) * abs(r1) ** 3,
                  r2 * r2 if r2 >= 0 else r2, f[3] / f34 if f34 != 0 else 0.0])
    q = np.where((q < 0) & (q > -1e-9), 0.0, q)            # rounding noise onto the bound
    return tuple(float(v) for v in np.where((q > 1) & (q < 1 + 1e-9), 1.0, q))


def intensity(w, mu):
    """I(mu)/I(1) for hybrid4 weights w."""
    return 1 - shapes(mu) @ np.asarray(w, float)


def is_physical(w, n=2001):
    """Positive and non-increasing towards the limb on a dense grid."""
    I = intensity(w, np.linspace(0.0, 1.0, n))
    return bool(I[0] >= -1e-10 and np.all(np.diff(I) >= -1e-10))


