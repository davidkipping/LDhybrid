def pack(a, dtype="<f4"):
    return base64.b64encode(zlib.compress(np.ascontiguousarray(a, dtype).tobytes(), 9)).decode()


def wrap(s, n=96):
    return "\n".join(f'    "{s[i:i + n]}"' for i in range(0, len(s), n))


