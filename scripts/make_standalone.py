def main():
    import make_standalone_mlx
    OUT.mkdir(exist_ok=True)
    t = I.LDTables(CDS, cache=False)
    for law in LAWS:
        nw = len(I.COEFFS[law])
        eps = [repr(e) for e in I.POLES[law]]
        doc, code, tail = LAW_TEXT[law]
        for grid, gridname in GRIDS.items():
            d = t.table(grid, law)
            for band, tag in BANDS.items():
                m = (d["band"] == band) & (d["method"] == "r")
                A = np.column_stack([d["teff"][m], d["logg"][m], d["mh"][m], d["coeffs"][m],
                                     d["mucri"][m], d["LCppm"][m]])
                mod = f"ldhybrid_{law}_{grid}_{tag}"
                G = I.GridSimplex(A[:, :3] / I.SCALE)
                assert G.n_empty == 0
                fmt = dict(law=law, gridname=gridname, band=band, mod=mod, grid=grid, n=len(A),
                           grid_code=GRID_SETUP + CORNERS_NP, fill_block=fill_block(G),
                           fill_doc=FILL_DOC.format(k=G.n_filled) if G.n_filled else "",
                           interp_doc=INTERP_DOC.format(fill=FILL_DOC.format(k=G.n_filled) if G.n_filled else ""),
                           nw=nw, nw1=nw + 1, ncol=nw + 2, eps=", ".join(eps),
                           wnames=", ".join(f"w{k + 1}" for k in range(nw)),
                           qnames=", ".join(f"q{k + 1}" for k in range(nw)),
                           law_doc=doc.format(**{f"eps{k}": e for k, e in enumerate(eps)}),
                           law_code=code, tail_doc=tail,
                           tmin=A[:, 0].min(), tmax=A[:, 0].max(), gmin=A[:, 1].min(), gmax=A[:, 1].max(),
                           mmin=A[:, 2].min(), mmax=A[:, 2].max(),
                           gridpts=wrap(pack(A[:, :3], "<f8")), data=wrap(pack(A[:, 3:])))
                if grid.startswith("mps"):
                    rows = [r for r in t.corrections() if r["Source"] == "MURaM" and r["Kind"] == "magnetic"
                            and r["Law"] == law and r["Band"] == band and float(r["mh"]) == 0.0]
                    T = sorted({float(r["Teff"]) for r in rows})
                    cd = []
                    for s in STATES:
                        rr = sorted([r for r in rows if r["State"] == s], key=lambda r: float(r["Teff"]))
                        assert [float(r["Teff"]) for r in rr] == T
                        vals = ", ".join("[" + ", ".join(f"{float(r[f'dw{k + 1}']):.6e}" for k in range(nw))
                                         + "]" for r in rr)
                        cd.append(f'    "{s}": [{vals}],')
                    corr = (T, "\n".join(cd))
                    fmt.update(corr_example='\n    r = coefficients(5600, 4.4, 0.0, correction="B100G")',
                               corr_doc=CORR_DOC.format(tlo=T[0], thi=T[-1]),
                               corr_block=CORR_BLOCK.format(tlo=T[0], thi=T[-1], cteff=[float(x) for x in T],
                                                            cdict="\n".join(cd)),
                               corr_arg=", correction=None", corr_key=", correction",
                               corr_apply=CORR_APPLY % nw, corr_ret=", correction=correction")
                else:
                    corr = None
                    fmt.update(corr_example="", corr_doc="", corr_block="", corr_arg="", corr_key="",
                               corr_apply="", corr_ret="")
                path = OUT / f"{mod}.py"
                path.write_text(TEMPLATE.format(**fmt))
                print(f"{path.relative_to(ROOT)}  {len(A)} models  {path.stat().st_size / 1e3:.0f} kB")
                path = OUT / f"{mod}_mlx.py"
                make_standalone_mlx.write(path, dict(fmt, _A=A), law, corr)
                print(f"{path.relative_to(ROOT)}  {path.stat().st_size / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
