def write(path, fmt, law, corr):
    """Write one MLX file. fmt: the numpy file's format dict; corr: None or
    (T, cdict text) for the MPS-ATLAS corrections."""
    from make_standalone import GRID_SETUP
    A = fmt["_A"]
    sub = dict(law=law, gridname=fmt["gridname"], band=fmt["band"], grid=fmt["grid"],
               mod=path.stem, np_mod=path.stem.removesuffix("_mlx"), nw=fmt["nw"], n=fmt["n"],
               fill_block=fmt["fill_block"], fill_doc=fmt["fill_doc"], grid_setup=GRID_SETUP,
               eps=fmt["eps"], wnames=fmt["wnames"], qnames=fmt["qnames"],
               law_doc=fmt["law_doc"], tail_doc=fmt["tail_doc"], elome_note=ELOME_NOTE[law],
               tmin=f"{A[:, 0].min():.0f}", tmax=f"{A[:, 0].max():.0f}",
               gmin=f"{A[:, 1].min():.1f}", gmax=f"{A[:, 1].max():.1f}",
               mmin=f"{A[:, 2].min():+.1f}", mmax=f"{A[:, 2].max():+.1f}",
               gridpts=fmt["gridpts"], data=fmt["data"],
               **LAW_MLX[law])
    if corr:
        T, cdict = corr
        sub.update(corr_example='\n    r = coefficients(5600.0, 4.4, 0.0, correction="B100G")',
                   corr_doc=fmt["corr_doc"],
                   corr_block=CORR_BLOCK.format(tlo=T[0], thi=T[-1], cteff=[float(x) for x in T], cdict=cdict),
                   corr_arg=", correction=None", corr_key=", correction", corr_check=CORR_CHECK,
                   corr_apply=CORR_APPLY, corr_ret=", correction=correction")
    else:
        sub.update(corr_example="", corr_doc="", corr_block="", corr_arg="", corr_key="",
                   corr_check="", corr_apply="", corr_ret="")
    path.write_text(TEMPLATE.substitute(sub))
